#!/usr/bin/env bash
# Build the versioned oncokbGene ANNOVAR database and its tarball.
#
# usage: build.sh <allCuratedGenes.json> <hg38.analysisSet.fa> <work-dir> [oncokb-data-version] [ensembl-release]
#
#   allCuratedGenes.json  OncoKB's /api/v1/utils/allCuratedGenes for the data version
#                         the cache answers with (v7.7 on 23 Nov 2026). Saved, not
#                         fetched here, so a rebuild is pinned to the file.
#   hg38.analysisSet.fa   the reference the pipeline aligns to (with its .fai).
#   work-dir              downloads, build files and the tarball go here.
#
# Needs docker and python3. ANNOVAR's retrieve_seq_from_fasta.pl runs from the
# production ANNOVAR image (pinned by digest) in a memory-capped container.
set -euo pipefail

curated=$(realpath "$1")
fasta=$(realpath "$2")
work=$(realpath -m "$3")
oncokb_version=${4:-v7.7}
ensembl=${5:-111}
here=$(cd "$(dirname "$0")" && pwd)
image="bergun/cancervar@sha256:ffad71ec62c2abcea5656102ed528b3a9db940af63b768bf32f7e5d9ba125754"
tag="oncokb-${oncokb_version}_ensembl-${ensembl}"
ens="https://ftp.ensembl.org/pub/release-${ensembl}"

mkdir -p "$work/dl" "$work/build"
cd "$work"
gtf="dl/Homo_sapiens.GRCh38.${ensembl}.gtf.gz"
pep="dl/Homo_sapiens.GRCh38.pep.all.r${ensembl}.fa.gz"
[ -s "$gtf" ] || curl -fsSL -o "$gtf" "$ens/gtf/homo_sapiens/Homo_sapiens.GRCh38.${ensembl}.gtf.gz"
[ -s "$pep" ] || curl -fsSL -o "$pep" "$ens/fasta/homo_sapiens/pep/Homo_sapiens.GRCh38.pep.all.fa.gz"

b="build"
python3 "$here/build_genepred.py" "$gtf" "$curated" "$b/hg38_oncokbGene.txt" "$b/build-report.json"

docker run --rm --network none --memory=16g --memory-swap=16g --cpus=4 -u "$(id -u):$(id -g)" \
  -v "$(dirname "$fasta"):/g:ro" -v "$work/$b:/db" --entrypoint perl "$image" \
  /tools/annovar/bin/retrieve_seq_from_fasta.pl /db/hg38_oncokbGene.txt -format refGene \
  -seqfile "/g/$(basename "$fasta")" -outfile /db/hg38_oncokbGeneMrna.fa

python3 "$here/build_isoforms.py" "$b/hg38_oncokbGene.txt" "$b/hg38_oncokbGeneMrna.fa" "$pep" \
  "$curated" "$b/hg38_oncokbGene.isoforms.tsv"

# ANNOVAR's header comment carries the build time; drop only the date so a rebuild
# is byte-identical (annotate_variation.pl reads "leftmost exon at" from it).
sed -i -E '/^>/s/ is generated by ANNOVAR on [^,]*,/ is generated by ANNOVAR,/' "$b/hg38_oncokbGeneMrna.fa"

dist="$work/dist/$tag"
rm -rf "$dist" && mkdir -p "$dist"
cp "$b/hg38_oncokbGene.txt" "$dist/hg38_oncokbGene.$tag.txt"
cp "$b/hg38_oncokbGeneMrna.fa" "$dist/hg38_oncokbGeneMrna.$tag.fa"
cp "$b/hg38_oncokbGene.isoforms.tsv" "$dist/hg38_oncokbGene.$tag.isoforms.tsv"
sha() { sha256sum "$1" | cut -d' ' -f1; }
cat > "$dist/hg38_oncokbGene.$tag.version" <<EOF
name=oncokbGene
version=$tag
oncokb_data_version=$oncokb_version
ensembl_release=$ensembl
allCuratedGenes_sha256=$(sha "$curated")
gtf=$(basename "$gtf") $(sha "$gtf")
pep=$(basename "$pep") $(sha "$pep")
reference_fasta=$(basename "$fasta")
annovar_image=$image
transcripts=$(wc -l < "$dist/hg38_oncokbGene.$tag.txt")
oncokb_isoforms=$(($(wc -l < "$dist/hg38_oncokbGene.$tag.isoforms.tsv") - 1))
known_exceptions=RYBP: incomplete ORF in Ensembl $ensembl, ANNOVAR gives no protein change on it
EOF
(cd "$dist" && sha256sum hg38_oncokbGene* > SHA256SUMS)
tarball="$work/dist/oncokbGene-$tag.tar.gz"
tar --sort=name --owner=0 --group=0 --numeric-owner --mtime=@0 -C "$work/dist" -cf - "$tag" | gzip -n -9 > "$tarball"
sha256sum "$tarball"
